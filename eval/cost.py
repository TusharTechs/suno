"""What SUNO costs to run, per note, per teacher and per child, from logged usage (not guesses).

Claude usage comes from the token counts the API returned while building the demo history
(samples/synthetic/demo_history.json: 8 teacher notes and a morning brief, run through the real
pipeline). Sarvam prices are the published pay-as-you-go rates. Assumptions are printed.

Run:  uv run python eval/cost.py
Writes eval/results/cost.md.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from server.pipeline.claude_client import PRICE_PER_MTOK  # noqa: E402

# Assumptions (override with environment variables).
INR_PER_USD = float(os.environ.get("INR_PER_USD", "88"))
SCHOOL_DAYS = int(os.environ.get("SCHOOL_DAYS", "200"))        # RTE norm for primary: at least 200 working days
CLASS_SIZE = int(os.environ.get("CLASS_SIZE", "30"))
NOTE_SECONDS = float(os.environ.get("NOTE_SECONDS", "60"))
# Sarvam, pay-as-you-go (sarvam.ai/api-pricing, 27 Oct 2026)
STT_INR_PER_MIN = 0.49
TTS_INR_PER_1K_CHARS = 3.00


def usd(u: dict) -> float:
    p = PRICE_PER_MTOK
    return (u["input_tokens"] * p["input"] + u["output_tokens"] * p["output"]
            + u.get("cache_write_tokens", 0) * p["cache_write"] + u.get("cache_read_tokens", 0) * p["cache_read"]) / 1e6


def compute() -> dict:
    fx = json.loads((ROOT / "samples/synthetic/demo_history.json").read_text())
    notes = [n["usage"] for n in fx["notes"] if n.get("usage")]
    brief = fx["brief"]
    note_usd = sum(usd(u) for u in notes) / len(notes)
    cached = sum(u.get("cache_read_tokens", 0) for u in notes) / max(1, sum(u["input_tokens"] + u.get("cache_read_tokens", 0) for u in notes))
    brief_usd = usd(brief["usage"]) if brief.get("usage") else 0.09
    brief_chars = len(brief["brief"]["text_hi"])
    stt_inr = NOTE_SECONDS / 60 * STT_INR_PER_MIN
    tts_inr = brief_chars / 1000 * TTS_INR_PER_1K_CHARS
    day_inr = (note_usd + brief_usd) * INR_PER_USD + stt_inr + tts_inr
    # ESTIMATE, not measured: brief at lower effort (assumed ~40% cheaper; it only words facts code
    # decided) and overnight Message Batches at half price.
    lean_day_inr = ((note_usd + brief_usd * 0.6) * 0.5) * INR_PER_USD + stt_inr + tts_inr
    return {"n_notes": len(notes), "note_usd": note_usd, "cached": cached, "brief_usd": brief_usd, "brief_chars": brief_chars,
            "stt_inr": stt_inr, "tts_inr": tts_inr, "day_inr": day_inr, "year_teacher_inr": day_inr * SCHOOL_DAYS,
            "child_year_inr": day_inr * SCHOOL_DAYS / CLASS_SIZE, "lean_child_year_inr": lean_day_inr * SCHOOL_DAYS / CLASS_SIZE,
            "lean_day_inr": lean_day_inr, "inr_per_usd": INR_PER_USD, "school_days": SCHOOL_DAYS, "class_size": CLASS_SIZE}


def main() -> None:
    c = compute()
    note_usd, cached, brief_usd, brief_chars = c["note_usd"], c["cached"], c["brief_usd"], c["brief_chars"]
    stt_inr, tts_inr, day_inr, lean_day_inr = c["stt_inr"], c["tts_inr"], c["day_inr"], c["lean_day_inr"]
    year_teacher, per_child_year, notes = c["year_teacher_inr"], c["child_year_inr"], range(c["n_notes"])
    lines = [
        "# What SUNO costs to run",
        "",
        "Generated by `eval/cost.py` from logged Claude usage (8 notes and a brief in `samples/synthetic/demo_history.json`, "
        "real API token counts) and Sarvam's published pay-as-you-go prices.",
        "",
        "**Assumptions:**",
        f"- ₹{INR_PER_USD:.0f} per US$",
        f"- {SCHOOL_DAYS} school days a year",
        f"- {CLASS_SIZE} children per class",
        f"- one {NOTE_SECONDS:.0f}-second note and one brief per school day",
        "",
        "| Per school day, per teacher | Cost |",
        "|---|---|",
        f"| Claude, reading the note (average of {len(notes)}; {cached:.0%} of input served from the prompt cache) | ${note_usd:.3f} (₹{note_usd * INR_PER_USD:.2f}) |",
        f"| Claude, wording the brief | ${brief_usd:.3f} (₹{brief_usd * INR_PER_USD:.2f}) |",
        f"| Sarvam speech-to-text, {NOTE_SECONDS:.0f} s at ₹{STT_INR_PER_MIN}/min | ₹{stt_inr:.2f} |",
        f"| Sarvam voice for the brief, {brief_chars} characters at ₹{TTS_INR_PER_1K_CHARS:.0f}/1,000 | ₹{tts_inr:.2f} |",
        f"| **Total** | **₹{day_inr:.2f}** |",
        "",
        f"- **Per teacher per year:** ₹{year_teacher:,.0f}",
        f"- **Per child per year:** ₹{per_child_year:,.0f}",
        f"- **Leaner configuration, same design (estimate, not measured):** brief at lower effort (assumed about 40% cheaper) and overnight batch processing at half price: about ₹{lean_day_inr:.2f} a day, ₹{lean_day_inr * SCHOOL_DAYS / CLASS_SIZE:,.0f} per child per year.",
        "- **One-off:** reading the attendance register from a photo costs about $0.02 per class (measured once).",
        "",
        "Not included: hosting (a single small server serves many schools) and data (a 60-second note is about 240 KB; a brief is about 300 KB of audio).",
    ]
    md = "\n".join(lines) + "\n"
    (ROOT / "eval/results/cost.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
