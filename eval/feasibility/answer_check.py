"""Feasibility test F2: can SUNO tell a right reading from a wrong one?

Real child voices from Pratham ASER: single Hindi words, each labelled right or
wrong by the ASER surveyor. Each clip goes to Sarvam speech-to-text (saaras:v4,
hi-IN, no hints about the expected word), and the transcript is compared with
the expected word. We report agreement with the surveyor's label, close to the
phone (as recorded) and in the SIMULATED classroom from voice_id.py.

    uv run --group speech python eval/feasibility/answer_check.py --n 200

Needs SARVAM_API_KEY in .env. Cost: about ₹30 per audio hour, so ~₹5 per run.
"""

from __future__ import annotations

import argparse
import io
import json
import math
import os
import time
import unicodedata
from difflib import SequenceMatcher

import httpx
import numpy as np
import pandas as pd
import soundfile as sf
from dotenv import load_dotenv
from scipy.signal import fftconvolve

from voice_id import (MANIFEST, NOISE_SNR_AT_1M, OUT, ROOT, SR, active_power, build_rirs, load,
                      make_noise_bed, norm_active, render, trim_active)

CONDITIONS = ["close", "calm@1m", "calm@4m", "noisy@2m"]
MATCH_THRESHOLD = 0.75


def normalise(s: str) -> str:
    s = unicodedata.normalize("NFC", s).replace("़", "")  # drop nukta: ड़ ~ ड
    return "".join(ch for ch in s if unicodedata.category(ch)[0] in "LM")


def similarity(a: str, b: str) -> float:
    a, b = normalise(a), normalise(b)
    return SequenceMatcher(None, a, b).ratio() if a and b else 0.0


def transcribe(client: httpx.Client, wav: np.ndarray, key: str) -> str:
    buf = io.BytesIO()
    sf.write(buf, wav, SR, format="WAV", subtype="PCM_16")
    for attempt in range(5):
        r = client.post(
            "https://api.sarvam.ai/speech-to-text",
            headers={"api-subscription-key": key},
            files={"file": ("answer.wav", buf.getvalue(), "audio/wav")},
            data={"model": "saaras:v4", "language_code": "hi-IN"},
        )
        if r.status_code == 429 or r.status_code >= 500:
            time.sleep(2 ** attempt)
            continue
        r.raise_for_status()
        return r.json().get("transcript", "")
    r.raise_for_status()
    return ""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200, help="clips; half labelled right, half wrong")
    ap.add_argument("--seed", type=int, default=11)
    args = ap.parse_args()
    load_dotenv(ROOT / ".env")
    key = os.environ.get("SARVAM_API_KEY")
    if not key:
        raise SystemExit("SARVAM_API_KEY is not set in .env")
    rng = np.random.default_rng(args.seed)

    df = pd.read_csv(MANIFEST)
    words = df[(df.level == "WD") & (df.speech_s >= 0.3) & df.is_correct.isin([True, False, "True", "False"])].copy()
    words["label"] = words.is_correct.astype(str) == "True"
    half = args.n // 2
    sample = pd.concat([
        words[words.label].sample(half, random_state=args.seed),
        words[~words.label].sample(half, random_state=args.seed),
    ]).reset_index(drop=True)
    print(f"{len(sample)} word readings from {sample.session.nunique()} children")

    rirs = build_rirs(rng)
    rest = df[~df.session.isin(sample.session) & df.level.isin(["WD", "L", "P"])].path.tolist()
    bed = make_noise_bed(rirs, rest, rng)
    ref = [fftconvolve(norm_active(trim_active(load(p))), rirs[("target", 1.0, 0.0)]) for p in sample.path[:60]]
    p_ref = float(np.mean([active_power(r) for r in ref]))
    gains = {s: math.sqrt(p_ref / (float(np.mean(bed ** 2)) * 10 ** (v / 10))) for s, v in NOISE_SNR_AT_1M.items()}

    rows = []
    with httpx.Client(timeout=60) as client:
        for i, r in sample.iterrows():
            x = norm_active(trim_active(load(r.path)))
            for cond in CONDITIONS:
                if cond == "close":
                    wav = x / (np.abs(x).max() + 1e-9) * 0.9
                else:
                    scen, dist = cond.split("@")
                    wav, _ = render(x, rirs[("target", float(dist[:-1]), 0.0)], bed, gains[scen], rng)
                text = transcribe(client, wav, key)
                sim = similarity(text, r.que_text)
                rows.append({"cond": cond, "expected": r.que_text, "heard": text, "similarity": round(sim, 3),
                             "label": bool(r.label), "pred": sim >= MATCH_THRESHOLD, "blank": not normalise(text)})
                time.sleep(1.0)  # starter plan: 60 requests a minute
            if i % 25 == 0:
                print(f"  {i}/{len(sample)}")
    res = pd.DataFrame(rows)

    summary, lines = [], [
        "# F2: telling a right reading from a wrong one (REAL child voices; rooms other than 'close' are SIMULATED)", "",
        f"Generated by `eval/feasibility/answer_check.py` (seed {args.seed}). {len(sample)} single Hindi words from Pratham ASER, "
        f"half labelled right and half wrong by the ASER surveyor. Sarvam saaras:v4 transcript vs expected word "
        f"(similarity >= {MATCH_THRESHOLD}).", "",
        "| Condition | Agreement with surveyor | Says 'right' when right | Says 'wrong' when wrong | Precision of 'wrong' | Empty transcripts |",
        "|---|---|---|---|---|---|"]
    for cond in CONDITIONS:
        g = res[res.cond == cond]
        tp = int((g.pred & g.label).sum()); tn = int((~g.pred & ~g.label).sum())
        fp = int((g.pred & ~g.label).sum()); fn = int((~g.pred & g.label).sum())
        s = {"condition": cond, "n": len(g), "agreement": (tp + tn) / len(g),
             "recall_right": tp / max(tp + fn, 1), "recall_wrong": tn / max(tn + fp, 1),
             "precision_wrong": tn / max(tn + fn, 1), "empty": float(g.blank.mean())}
        summary.append(s)
        lines.append(f"| {cond} | {s['agreement']:.0%} | {s['recall_right']:.0%} | {s['recall_wrong']:.0%} | "
                     f"{s['precision_wrong']:.0%} | {s['empty']:.0%} |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "f2_answer_check.json").write_text(json.dumps({"summary": summary}, indent=1))
    res.drop(columns=["heard"]).to_csv(OUT / "f2_answer_check_rows.csv", index=False)
    (OUT / "f2_answer_check.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
