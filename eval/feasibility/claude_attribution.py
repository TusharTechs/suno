"""Feasibility test F3: does Claude + code say "not sure" on the mentor's hard cases?

Runs Claude call 1 (rebuild moments) on the SYNTHETIC lessons in
samples/synthetic/attribution_lessons.json: pointing without a name, shared
first names, a friend answering, chorus, a teacher praising a wrong answer,
a tap that disagrees with the name. For each answer we know who really spoke
and which attributions are acceptable (often only "not known").

    uv run python eval/feasibility/claude_attribution.py

Needs ANTHROPIC_API_KEY in .env. Cost: a few cents per run.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from server.pipeline.claude_client import MODEL, Usage  # noqa: E402
from server.pipeline.claude_moments import rebuild_moments  # noqa: E402

OUT = ROOT / "eval/results"


def who(moments: list[dict], response_seg: str):
    for m in moments:
        if response_seg in m["response_seg_ids"]:
            return m["addressee_child_id"]
    return None


def main() -> None:
    data = json.loads((ROOT / "samples/synthetic/attribution_lessons.json").read_text())
    roster = data["roster"]
    names = {c["child_id"]: f'{c["first_name"]} ({c["roll_no"]})' for c in roster}
    usage = Usage()
    rows = []
    for L in data["lessons"]:
        raw, verified, problems = rebuild_moments(roster, L["lesson"], L["segments"], L["taps"], usage=usage)
        for mid, action, why in problems:
            print(f'  {L["lesson"]["lesson_id"]} {mid}: {action}: {why}')
        for t in L["truth"]:
            a, b = who(raw, t["response_seg"]), who(verified, t["response_seg"])
            rows.append({"lesson": L["lesson"]["lesson_id"], "case": t["case"], "accept": t["accept"],
                         "claude": a, "checked": b, "claude_ok": a in t["accept"], "checked_ok": b in t["accept"]})

    def label(c):
        return "not known" if c is None else names.get(c, c)

    def score(key):
        named = [r for r in rows if r[key] is not None]
        wrong = [r for r in named if r[key] not in r["accept"]]
        return len(rows), sum(r[f"{key}_ok"] for r in rows), len(named), len(wrong)

    lines = ["# F3: attribution on hard cases (SYNTHETIC transcripts)", "",
             f"Generated by `eval/feasibility/claude_attribution.py` with `{MODEL}`. "
             f"{len(rows)} answers across {len(data['lessons'])} synthetic lessons. 'Not known' is the right answer "
             "whenever the transcript and taps cannot say who spoke.", "",
             "| Lesson | Case | Acceptable | Claude alone | Claude + code checks |", "|---|---|---|---|---|"]
    for r in rows:
        mark = lambda ok: "✓" if ok else "✗"
        lines.append(f'| {r["lesson"]} | {r["case"]} | {" or ".join(label(a) for a in r["accept"])} | '
                     f'{label(r["claude"])} {mark(r["claude_ok"])} | {label(r["checked"])} {mark(r["checked_ok"])} |')
    lines.append("")
    for key, title in (("claude", "Claude alone"), ("checked", "Claude + code checks")):
        n, ok, named, wrong = score(key)
        lines.append(f"- **{title}:** {ok}/{n} handled correctly; named a child {named} times, wrongly {wrong} times.")
    lines.append(f"- Tokens: {usage.input_tokens} in, {usage.output_tokens} out, "
                 f"{usage.cache_read_tokens} cache reads. Cost ≈ ${usage.usd:.3f}.")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "f3_claude_attribution.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
