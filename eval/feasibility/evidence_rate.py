"""How fast can SUNO learn each child's level, skill by skill? A MODEL, not a measurement.

SUNO names a child's status on a skill only after 3 confident moments on at
least 2 days. This simulates a class of 35 over 12 school weeks under four
ways of collecting evidence, and reports how many child x skill cells reach
that bar. Every input below is an assumption, stated so it can be argued with.

    uv run python eval/feasibility/evidence_rate.py
"""

from __future__ import annotations

import numpy as np

from voice_id import OUT

N_CHILDREN = 35
ATTENDANCE = 0.80          # share of children present on a given day
SKILLS = ["letters (akshara)", "vowel signs (matra)", "blending", "words", "fluency", "meaning (comprehension)"]
FOCUS_PER_WEEK = 2         # structured pedagogy: a week's lessons centre on ~2 skills
DAYS, WEEKS, RUNS = 5, 12, 300
MIN_MOMENTS, MIN_DAYS = 3, 2

SCENARIOS = {
    # name: (description, teacher minutes a day)
    "A. Listen to ordinary lessons": (
        "Named individual answers in the reading period (4-12 a day, mostly the same few children), "
        "only on this week's focus skills; 60% survive speech recognition, attribution and the gate", 0.0),
    "B. Tap on 5 planned call-ons": (
        "Planner picks the 5 least-heard children present; 2 items each on this week's focus skills; 80% survive", 1.0),
    "C. 90-second reading ladder, 5 children a day": (
        "Planner picks 5 least-heard children; each reads ~8 items spanning all 6 skills plus one meaning "
        "question; 80% of items survive", 7.5),
    "D. 90-second reading ladder, 3 children a day": ("As C, 3 children a day", 4.5),
}


def simulate(scenario: str, rng: np.random.Generator) -> np.ndarray:
    """Returns, per week, the share of child x skill cells that meet the naming rule."""
    S = len(SKILLS)
    moments = np.zeros((N_CHILDREN, S), dtype=int)
    days_seen = [[set() for _ in range(S)] for _ in range(N_CHILDREN)]
    # Who gets called on in ordinary lessons is unequal: a few children answer most questions.
    eagerness = rng.pareto(1.2, N_CHILDREN) + 0.1
    weekly = []
    day = 0
    for w in range(WEEKS):
        focus = rng.choice(S, FOCUS_PER_WEEK, replace=False)
        for _ in range(DAYS):
            day += 1
            present = np.flatnonzero(rng.random(N_CHILDREN) < ATTENDANCE)
            if scenario.startswith("A"):
                k = int(rng.integers(4, 13))
                p = eagerness[present] / eagerness[present].sum()
                events = [(int(rng.choice(present, p=p)), int(rng.choice(focus)), 0.6) for _ in range(k)]
            else:
                n_kids = 3 if scenario.startswith("D") else 5
                total = moments.sum(axis=1)
                picked = present[np.argsort(total[present] + rng.random(len(present)))[:n_kids]]
                events = []
                for c in picked:
                    if scenario.startswith("B"):
                        events += [(int(c), int(rng.choice(focus)), 0.8) for _ in range(2)]
                    else:
                        items = list(range(S)) + list(rng.choice(S, 2))   # ~8 items across the ladder
                        events += [(int(c), int(s), 0.8) for s in items]
            for c, s, keep in events:
                if rng.random() < keep:
                    moments[c, s] += 1
                    days_seen[c][s].add(day)
        ok = np.array([[moments[c, s] >= MIN_MOMENTS and len(days_seen[c][s]) >= MIN_DAYS
                        for s in range(S)] for c in range(N_CHILDREN)])
        weekly.append((ok.mean(), (ok.all(axis=1)).mean(), (moments.sum(axis=1) == 0).mean()))
    return np.array(weekly)


def main() -> None:
    rng = np.random.default_rng(3)
    lines = ["# How fast can SUNO learn each child's level, skill by skill? (MODEL, not measured)", "",
             "Generated by `eval/feasibility/evidence_rate.py`. Class of 35, 80% attendance, 6 reading skills, "
             f"naming rule = {MIN_MOMENTS} confident moments on {MIN_DAYS}+ days, {RUNS} simulated terms. "
             "All inputs are assumptions listed in the script.", "",
             "| How evidence is collected | Teacher time a day | Child x skill cells known after 2 weeks | after 4 weeks | after 8 weeks | Children with ALL 6 skills known after 4 weeks | Children never heard after 4 weeks |",
             "|---|---|---|---|---|---|---|"]
    for name, (desc, minutes) in SCENARIOS.items():
        res = np.median(np.stack([simulate(name, rng) for _ in range(RUNS)]), axis=0)
        lines.append(f"| {name} | {minutes:g} min | {res[1, 0]:.0%} | {res[3, 0]:.0%} | {res[7, 0]:.0%} | "
                     f"{res[3, 1]:.0%} | {res[3, 2]:.0%} |")
    lines += ["", "Scenarios:"] + [f"- **{k}:** {v[0]}." for k, v in SCENARIOS.items()]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "evidence_rate.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
