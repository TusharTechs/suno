"""Feasibility test F1-real: the mentor's home experiment, scored.

2-5 people play a classroom. Each person first records a ~20 s voice sample
close to the phone (enrolment). Then one person teaches and calls on the
others, who answer from 1, 2, 4 and 6 m while the phones record. This script
cuts out each labelled answer and checks whether voice matching picks the
right person, per phone placement and distance. REAL recordings.

Folder layout (data/raw/ is git-ignored; never commit it):

    data/raw/<session>/enrol/<name>.m4a        one per person (any audio format ffmpeg reads)
    data/raw/<session>/phone_<placement>.m4a   e.g. phone_worn.m4a, phone_desk.m4a
    data/raw/<session>/labels.txt              Audacity label export, made on ONE phone's recording

Each label is "<name>@<distance in m>", e.g. "asha@4". Label only the
answers, not the teacher. Put the labelled phone's placement in --labelled-on;
the other recordings are aligned to it automatically.

    uv run --group speech python eval/feasibility/home_test.py data/raw/<session> --labelled-on worn
"""

from __future__ import annotations

import argparse
import subprocess
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy.signal import fftconvolve

from voice_id import ROOT, SR, Embedder, norm_active, trim_active

OUT = ROOT / "eval/results"


def read_audio(path: Path) -> np.ndarray:
    raw = subprocess.run(
        ["ffmpeg", "-v", "quiet", "-i", str(path), "-f", "f32le", "-ac", "1", "-ar", str(SR), "pipe:1"],
        capture_output=True, check=True,
    ).stdout
    return np.frombuffer(raw, dtype=np.float32).copy()


def read_labels(path: Path) -> list[tuple[float, float, str, float]]:
    rows = []
    for line in path.read_text().splitlines():
        parts = line.strip().split("\t")
        if len(parts) < 3 or "@" not in parts[2]:
            continue
        name, dist = parts[2].rsplit("@", 1)
        rows.append((float(parts[0]), float(parts[1]), name.strip().lower(), float(dist)))
    return rows


def offset_seconds(ref: np.ndarray, other: np.ndarray, rate: int = 1000) -> float:
    """Lag of `other` behind `ref`, from cross-correlating loudness envelopes."""
    def env(x):
        hop = SR // rate
        n = len(x) // hop
        e = np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1))
        return (e - e.mean()) / (e.std() + 1e-9)
    a, b = env(ref), env(other)
    xc = fftconvolve(b, a[::-1])
    return (int(np.argmax(xc)) - (len(a) - 1)) / rate


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("session", type=Path)
    ap.add_argument("--labelled-on", required=True, help="placement whose recording the labels were made on")
    ap.add_argument("--models", default="ecapa,wavlm")
    args = ap.parse_args()
    s = args.session

    enrol_files = sorted(p for p in (s / "enrol").iterdir() if not p.name.startswith("."))
    names = [p.stem.lower() for p in enrol_files]
    phones = {p.stem.removeprefix("phone_"): read_audio(p) for p in sorted(s.glob("phone_*")) if p.suffix != ".txt"}
    labels = read_labels(s / "labels.txt")
    unknown = {n for _, _, n, _ in labels} - set(names)
    if unknown:
        raise SystemExit(f"labels name people with no enrolment clip: {sorted(unknown)}")
    ref = phones[args.labelled_on]
    shifts = {k: (0.0 if k == args.labelled_on else offset_seconds(ref, v)) for k, v in phones.items()}
    print(f"{len(names)} people, {len(labels)} labelled answers, phones: "
          + ", ".join(f"{k} (shift {v:+.2f}s)" for k, v in shifts.items()))

    enrol = [norm_active(trim_active(read_audio(p)))[: 30 * SR] for p in enrol_files]
    clips, meta = [], []
    for phone, x in phones.items():
        for t0, t1, name, dist in labels:
            a, b = int((t0 + shifts[phone]) * SR), int((t1 + shifts[phone]) * SR)
            if a < 0 or b > len(x) or b - a < SR // 5:
                continue
            seg = x[a:b]
            clips.append(seg / (np.abs(seg).max() + 1e-9) * 0.9)
            meta.append((phone, dist, names.index(name)))

    lines = [f"# F1-real: voice matching on a home recording ({s.name}), REAL audio", "",
             f"{len(names)} people enrolled; chance = {1 / len(names):.0%}. Generated by `eval/feasibility/home_test.py`.", ""]
    for model in args.models.split(","):
        emb = Embedder(model)
        E, T = emb.enrol(enrol), emb(clips)
        S = T @ E.T
        cells = defaultdict(lambda: [0, 0])
        for (phone, dist, truth), row in zip(meta, S):
            cells[(phone, dist)][0] += int(np.argmax(row) == truth)
            cells[(phone, dist)][1] += 1
        dists = sorted({d for _, d in cells})
        lines += [f"## {model}", "", "| Phone | " + " | ".join(f"{d:g} m" for d in dists) + " |",
                  "|---|" + "---|" * len(dists)]
        for phone in phones:
            row = [f"{cells[(phone, d)][0]}/{cells[(phone, d)][1]}" if cells[(phone, d)][1] else "–" for d in dists]
            lines.append(f"| {phone} | " + " | ".join(row) + " |")
        lines.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    out = OUT / f"home_{s.name}.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
