"""Checks behind F1: is the ASER audio a fair test of voice matching?

1. Recording device: 35 children from one device vs 35 from 35 devices,
   matching 10 s of reading against another 10 s (ECAPA). If one device
   scored much lower, a shared surveyor voice or room would be the cause.
2. Whose voice: median pitch of paragraph readings (children ~250 Hz, adults lower).
3. Bandwidth: where the long-term spectrum falls 30 dB below its peak.

    uv run --group speech python eval/feasibility/sanity_checks.py
"""

from __future__ import annotations

from collections import defaultdict

import numpy as np
import pandas as pd

from voice_id import MANIFEST, OUT, SR, Embedder, load, norm_active, select_pool, trim_active


def f0_frames(x: np.ndarray, frame: int = 640) -> list[float]:
    out = []
    peak = np.abs(x).max() + 1e-9
    for i in range(0, len(x) - frame, frame):
        f = x[i: i + frame]
        if np.sqrt(np.mean(f ** 2)) < 0.02 * peak:
            continue
        f = f - f.mean()
        ac = np.correlate(f, f, "full")[frame - 1:]
        lo, hi = SR // 500, SR // 80
        k = lo + int(np.argmax(ac[lo:hi]))
        if ac[k] > 0.4 * ac[0]:
            out.append(SR / k)
    return out


def main() -> None:
    rng = np.random.default_rng(5)
    df = pd.read_csv(MANIFEST, dtype={"device_id": str})
    pool, _ = select_pool(df, 5000, 5, rng)
    by = defaultdict(list)
    for c in pool:
        by[c["device"]].append(c)
    same = by[max(by, key=lambda d: len(by[d]))][:35]
    mixed = [by[d][0] for d in rng.permutation(list(by))][:35]
    emb = Embedder("ecapa")

    def cat(paths):
        return np.concatenate([norm_active(trim_active(load(p))) for p in paths])

    def acc(cs):
        a = emb([cat(c["enrol"][: max(1, len(c["enrol"]) // 2)]) for c in cs])
        b = emb([cat(c["enrol"][len(c["enrol"]) // 2:] or c["enrol"][-1:]) for c in cs])
        return float(np.mean((b @ a.T).argmax(1) == np.arange(len(cs))))

    acc_same, acc_mixed = acc(same), acc(mixed)

    paras = df[df.level == "P"].sample(40, random_state=1).path
    f0 = np.array([f for p in paras for f in f0_frames(load(p))])
    spec = np.zeros(257)
    for p in paras:
        x = load(p)
        for i in range(0, len(x) - 512, 256):
            spec += np.abs(np.fft.rfft(x[i: i + 512] * np.hanning(512))) ** 2
    db = 10 * np.log10(spec / spec.max() + 1e-12)
    cutoff = float(np.fft.rfftfreq(512, 1 / SR)[np.where(db > -30)[0].max()])

    lines = ["# F1 sanity checks (REAL ASER audio)", "", "Generated by `eval/feasibility/sanity_checks.py`.", "",
             f"- 10 s vs 10 s of the same child's reading, 35 children, ECAPA: **{acc_same:.0%}** matched when all "
             f"35 were recorded on one device, **{acc_mixed:.0%}** across 35 devices.",
             f"- Median pitch of paragraph readings: **{np.median(f0):.0f} Hz**; "
             f"{np.mean(f0 < 180):.0%} of voiced frames below 180 Hz (adult range).",
             f"- Spectrum stays within 30 dB of its peak up to **{cutoff:.0f} Hz**."]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "f1_sanity.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
