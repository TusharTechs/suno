"""Score SUNO on REAL human speech: people read the scripts in docs/real-notes-protocol.md aloud
into ordinary phones; this runs each recording through Sarvam speech-to-text and SUNO's real
pipeline and scores it against the script's ground truth (same scoring as the simulation).

Recordings go in data/raw/real_notes/ (git-ignored), named <note id>_<setting>.<ext>, e.g.
note03_fan.m4a (any format a phone records). The same note can be read in several settings;
results are reported overall and per setting.

Run:  uv run python eval/real_notes/score.py
Writes eval/results/real_notes.md. Costs about $0.04 of Claude credit per recording.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from eval.sim.run_pipeline_sim import answer_questions, pct, score_note  # noqa: E402
from server.pipeline import asr, claude_observations  # noqa: E402
from server.pipeline.claude_client import Usage  # noqa: E402

RAW = ROOT / "data" / "raw" / "real_notes"
LESSON = json.loads((ROOT / "samples/synthetic/demo_class.json").read_text())["lesson"]


def main() -> None:
    scripts = json.loads((ROOT / "eval/real_notes/scripts.json").read_text())
    by_id = {n["id"]: n for n in scripts["notes"]}
    files = sorted(f for f in RAW.glob("*") if f.is_file() and f.name.split("_")[0].split(".")[0] in by_id)
    if not files:
        raise SystemExit(f"no recordings in {RAW} (name them note01_<who>_<where>.m4a and so on)")
    before, after, usage, rows = Counter(), Counter(), Usage(), []
    per_setting: dict[str, Counter] = {}
    for f in files:
        note = by_id[f.name.split("_")[0].split(".")[0]]
        heard = asr.transcribe(f.read_bytes(), scripts["roster"], LESSON)
        out = claude_observations.extract(asr.sentences(heard["transcript"]), scripts["roster"], LESSON, [], usage=usage)
        b = score_note(note["statements"], [dict(r) for r in out["records"]], out["follow_ups"])
        taps = answer_questions(out, note["statements"])
        a = score_note(note["statements"], out["records"], out["follow_ups"])
        before.update(b); after.update(a)
        setting = f.stem.split("_", 1)[1] if "_" in f.stem else "unspecified"
        per_setting.setdefault(setting, Counter()).update(b)
        rows.append((f.name, heard["seconds"], b, a, taps, heard["transcript"]))
        print(f"{f.name}: {heard['seconds']} s, evidence {b['evidence']}, wrong child {b['wrong_child_evidence']}, "
              f"clear obs → evidence {b['expect_evidence_became_evidence']}/{b['expect_evidence']}", flush=True)
    B, A = before, after
    lines = [
        "# SUNO on real human speech (scripted notes read aloud)",
        "",
        f"Generated by `eval/real_notes/score.py`: {len(files)} recordings by one real speaker of the scripts in "
        "`docs/real-notes-protocol.md` (a fictional class; ground truth known per statement), recorded on ordinary "
        "phones in ordinary rooms, run through Sarvam speech-to-text and SUNO's real pipeline. Real voices, scripted words: "
        "this tests speech recognition and the pipeline, not what real teachers choose to say.",
        "",
        "| | Result |",
        "|---|---|",
        f"| Evidence records about the wrong child | {pct(B['wrong_child_evidence'], B['evidence'])} |",
        f"| Evidence records whose right/wrong direction matches the script | {pct(B['evidence_direction_ok'], B['evidence'])} |",
        f"| Opinions, labels and vague remarks that became evidence | {pct(B['not_evidence_became_evidence'], B['expect_not_evidence'])} |",
        f"| Labels repeated by SUNO | {B['banned_in_output']} (in {B['statements_with_label']} statements that used one) |",
        f"| Specific observations about a clearly named child that became evidence | {pct(B['expect_evidence_became_evidence'], B['expect_evidence'])} |",
        f"| …with an unclear name, after the teacher's one tap | {pct(A['expect_ask_then_evidence_became_evidence'], A['expect_ask_then_evidence'])} |",
        f"| Absences recorded | {pct(B['absent_found'], B['expect_absent'])} |",
        "",
        "## By setting",
        "",
        "| Setting | Recordings | Wrong-child evidence | Direction right | Clear observations → evidence |",
        "|---|---|---|---|---|",
    ] + [f"| {k} | {sum(1 for r in rows if (r[0].split('.')[0].split('_', 1) + ['unspecified'])[1] == k)} | "
         f"{pct(c['wrong_child_evidence'], c['evidence'])} | {pct(c['evidence_direction_ok'], c['evidence'])} | "
         f"{pct(c['expect_evidence_became_evidence'], c['expect_evidence'])} |" for k, c in sorted(per_setting.items())] + [
        "",
        "One speaker (an adult man); most primary teachers are women. Read with the simulation results, not instead of them.",
        "",
        "| Recording | Seconds | Evidence | Wrong child | Clear observations → evidence |",
        "|---|---|---|---|---|",
    ] + [f"| {n} | {s} | {b['evidence']} | {b['wrong_child_evidence']} | {b['expect_evidence_became_evidence']}/{b['expect_evidence']} |"
         for n, s, b, a, t, _ in rows] + ["", f"Claude spend: ${usage.usd:.2f}."]
    (ROOT / "eval/results/real_notes.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
