"""Stage B, ASER-calibrated (SIMULATED children, PUBLISHED distributions).

The same 12-week term as run_term_sim.py, with SUNO's real tracker and planner. The classes are built
from published data instead of our guesses:
  - each child's reading level is drawn from ASER 2024's Std II table for the state;
  - each child has her own absence rate, spread around the state's published attendance
    (some children are absent often, which is harder for any listening plan).
Sources and the two assumptions this needs are in eval/sim/aser2024.json and eval/sim/world.py.

Run:  uv run python eval/sim/run_aser_sim.py --runs 200
Writes eval/results/sim_aser.md and .json. No API calls.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from eval.sim import run_term_sim as term  # noqa: E402
from eval.sim.world import ASER, aser_absence, aser_reading_dist  # noqa: E402

STATES = ["India", "Uttar Pradesh", "Bihar", "Madhya Pradesh", "Rajasthan"]
NAMES = {"no_list": "Perfect diary, no list", "list_50": "SUNO, list followed 50%", "list_80": "SUNO, list followed 80%"}
METRICS = [
    ("children_found", "Children who truly need support in Hindi reading whom SUNO flags"),
    ("children_flag_precision", "Of the children SUNO flags, how many truly need support"),
    ("quiet_with_evidence", "Quietest third of the class with any evidence"),
    ("quiet_struggling_found", "Quietest third: struggling child × skill cells flagged"),
    ("level_within_one", "Stated reading level within one of the true level"),
]


def mean(xs):
    xs = [x for x in xs if x == x]
    return sum(xs) / len(xs) if xs else float("nan")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=200)
    a = ap.parse_args()
    rates = term.measured_rates()
    res = {}
    for st in STATES:
        world = {"reading_dist": aser_reading_dist(st), "absence": aser_absence(st)}
        agg = {arm: defaultdict(lambda: defaultdict(list)) for arm in term.ARMS}
        flags = {arm: [0, 0] for arm in term.ARMS}
        for i in range(a.runs):
            for arm in term.ARMS:
                r = term.run_once(arm, 5000 + i, rates, world)
                for wk in term.CHECKPOINTS:
                    for m, v in r[wk].items():
                        agg[arm][wk][m].append(v)
                flags[arm][0] += r[12]["flags"]; flags[arm][1] += r[12]["flags_right"]
        res[st] = {arm: {"weeks": {w: {m: mean(agg[arm][w][m]) for m, _ in METRICS} for w in term.CHECKPOINTS},
                         "flags_per_class_w12": flags[arm][0] / a.runs,
                         "flag_precision_w12": flags[arm][1] / flags[arm][0] if flags[arm][0] else None}
                   for arm in term.ARMS}
        print(f"{st}: done", flush=True)

    pct = lambda x: "–" if x is None or x != x else f"{x:.0%}"
    L = ["# A 12-week term in ASER-calibrated classrooms (SIMULATED children, PUBLISHED distributions)", "",
         f"Generated by `eval/sim/run_aser_sim.py`: {a.runs} simulated classes of {term.SIZE} enrolled children per state, "
         f"{term.WEEKS} weeks, {term.PER_DAY} children noticed a day, SUNO's real tracker and planner.", "",
         "**What is real here:** each class's reading levels follow ASER 2024's published Std II table for the state, and absence "
         "follows the state's published attendance in government primary schools (Pratham / ASER Centre, `eval/sim/aser2024.json`).", "",
         "**What is not:** the children, the teacher and her notes are simulated. Two assumptions: ASER's single \"word\" level is split "
         "half simple words, half words with vowel signs; each child's absence rate is spread around the state average (Beta, concentration 4). "
         "ASER's table covers government and private schools together; government-school children read lower. "
         f"Per-statement error rates: {rates['source']}.", "",
         "| State | Beginner | Letter | Word | Paragraph | Story | Children present |", "|---|---|---|---|---|---|---|"]
    for st in STATES:
        L.append(f"| {st} | " + " | ".join(f"{x:.1f}%" for x in ASER["reading_std2"][st]) + f" | {ASER['attendance_primary'][st]:.1f}% |")
    L.append("")
    for m, title in METRICS:
        L += [f"## {title}", "", "| State | " + " | ".join(NAMES.values()) + " |", "|---|---|---|---|"]
        for wk in (2, 8):
            for st in STATES:
                L.append(f"| {st}, week {wk} | " + " | ".join(pct(res[st][arm]["weeks"][wk][m]) for arm in term.ARMS) + " |")
        L.append("")
    L += ["## Precision of \"needs support\" flags at week 12", "", "| State | " + " | ".join(NAMES.values()) + " |", "|---|---|---|---|"]
    for st in STATES:
        L.append(f"| {st} | " + " | ".join(f"{pct(res[st][arm]['flag_precision_w12'])} ({res[st][arm]['flags_per_class_w12']:.0f} flags)" for arm in term.ARMS) + " |")
    md = "\n".join(L) + "\n"
    (ROOT / "eval/results/sim_aser.md").write_text(md)
    (ROOT / "eval/results/sim_aser.json").write_text(json.dumps({"label": "SIMULATED children, ASER 2024 published distributions",
                                                                  "runs": a.runs, "rates": rates, "results": res}, indent=1))
    print(md)


if __name__ == "__main__":
    main()
